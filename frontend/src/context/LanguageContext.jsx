export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(() => {
    return localStorage.getItem('health_passport_lang') || 'en';
  });

  useEffect(() => {
    localStorage.setItem('health_passport_lang', lang);
    document.documentElement.setAttribute('lang', lang);
  }, [lang]);

  const currentLanguage = LANGUAGES.find(l => l.id === lang) || LANGUAGES[0];

  const t = (key) => {
    return TRANSLATIONS[lang]?.[key] || TRANSLATIONS.en[key] || key;
  };

  return (
    <LanguageContext.Provider value={{ lang, setLang, currentLanguage, languages: LANGUAGES, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
}
